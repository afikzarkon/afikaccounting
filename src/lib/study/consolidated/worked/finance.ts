const n = (v: number) => v.toLocaleString("en-US");
const S = SHARES8_FIG;
const B = BOND8;
const r2 = (v: number) => Math.round(v * 100) / 100 + 0;
const fac = (r: number, k: number) => (1 / (1 + r) ** k).toFixed(6);
const ann = (r: number, k: number) => pv(r, k, 1).toFixed(6);
const je = (cap: string, lines: [string, number | "", number | ""][]): WTable => ({ cap, head: ["חשבון", "חובה", "זכות"], rows: lines.map((l) => ({ c: l })) });
/** One company's amortized-cost schedule, a row a year; the last year's interest closes the balance on the face. */
const schedule = (cap: string, from: number, rows: { open: number; interest: number; close: number }[], rate: string): WTable => ({
  cap,
  head: ["", "פתיחה", "הכנסות מימון", "תקבול", "סגירה", "חישוב"],
  rows: rows.map((r, i) => ({
    c: [String(from + i), r.open, r.interest, -4_500, r.close, i < rows.length - 1 ? `\`${n(r.open)} × ${rate}\`` : `\`100,000 + 4,500 − ${n(r.open)}\`: סוגר על הנקוב`],
  })),
});

