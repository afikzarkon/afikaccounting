  const c = row(cons);
  const names = [label, "הוצאות מסים", "רווח נקי", "רווח כולל אחר, נטו"];
  const head = ["", "דולב", "התאמה", "מאוחד", ...(how ? ["חישוב"] : [])];
  return { cap, head, rows: names.map((nm, i) => ({ c: [nm, s[i], c[i] - s[i] + 0, c[i], ...(how ? [how[i]] : [])], res: i >= 2 })) };
