const n = (v: number) => v.toLocaleString("en-US");
const ann = (r: number, k: number) => pv(r, k, 1).toFixed(6);
const fac = (r: number, k: number) => (1 / (1 + r) ** k).toFixed(6);
const je = (cap: string, lines: [string, number | "", number | ""][]): WTable => ({ cap, head: ["חשבון", "חובה", "זכות"], rows: lines.map((l) => ({ c: l })) });
const r0 = (v: number) => Math.round(v) + 0;
/** A bond's value as a sheet shows it: two rounded lines and their sum. */
const bondPv = (r: number, k: number, coupon: number, face: number) => {
  const c = agora(coupon * pv(r, k, 1));
  const f = agora(face / (1 + r) ** k);
  return { c, f, total: agora(c + f) };
};

