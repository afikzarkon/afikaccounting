const n = (v: number) => v.toLocaleString("en-US");

/** One payment cut into its parts, drawn to scale. */
function SplitBar({ label, parts }: { label: string; parts: { name: string; value: number; color: string }[] }) {
  const total = parts.reduce((sum, p) => sum + p.value, 0);
  return (
    <figure role="img" aria-label={label}>
      <div className="flex h-12 overflow-hidden rounded-lg border border-line-strong">
        {parts.map((p) => (
          <span key={p.name} className="num flex items-center justify-center text-[13px] font-semibold text-fg" style={{ width: `${(p.value / total) * 100}%`, background: `color-mix(in oklab, ${p.color} 22%, transparent)` }}>
            <bdi dir="ltr">{n(p.value)}</bdi>
          </span>
        ))}
      </div>
      <figcaption className="mt-1.5 flex justify-between gap-3 text-[13.5px] text-muted">
        {parts.map((p) => (
          <span key={p.name}>{p.name}</span>
        ))}
      </figcaption>
    </figure>
  );
}

