/** How much of a shared asset each customer holds, drawn to scale. */
function ShareBars({ label, rows }: { label: string; rows: { name: string; share: number; verdict: string }[] }) {
  return (
    <figure role="img" aria-label={label} className="space-y-3 rounded-2xl border border-line bg-surface p-3.5">
      {rows.map((r) => (
        <div key={r.name}>
          <p className="flex flex-wrap items-baseline justify-between gap-x-3 text-[14px]">
            <span className="font-semibold text-fg">
              {r.name}: <bdi dir="ltr" className="num">{r.share}%</bdi>
            </span>
            <span className="text-muted">{r.verdict}</span>
          </p>
          <div className="mt-1 h-5 overflow-hidden rounded-md border border-line-strong bg-surface-2">
            <div className="h-full" style={{ width: `${r.share}%`, background: "color-mix(in oklab, var(--accent) 45%, transparent)" }} />
          </div>
        </div>
      ))}
    </figure>
  );
}

/** Where something goes, step by step: a row on a wide screen, a column on a phone. */
function Flow({ label, steps }: { label: string; steps: string[] }) {
  return (
    <figure role="img" aria-label={label} className="flex flex-col items-stretch gap-1 sm:flex-row sm:items-center">
      {steps.map((s, i) => (
        <Fragment key={s}>
          {i > 0 && (
            <>
              <ArrowDown className="mx-auto h-4 w-4 shrink-0 text-subtle sm:hidden" aria-hidden />
              <ArrowRight className="hidden h-4 w-4 shrink-0 text-subtle sm:block rtl:rotate-180" aria-hidden />
            </>
          )}
          <span className="flex-1 rounded-lg bg-surface px-2.5 py-1.5 text-center text-[13.5px] text-fg ring-1 ring-line">{s}</span>
        </Fragment>
      ))}
    </figure>
  );
}

/** One part of a contract, test by test: the test and its result on one line, the reason beside it; narrow enough for a phone. */
function TestTable({ rows, verdict }: { rows: [string, string, string][]; verdict: string }) {
  return (
    <table className="block w-full text-[14px] sm:table">
      <thead className="sr-only sm:not-sr-only sm:table-header-group">
        <tr className="text-muted">
          <th className="px-2 py-1 text-start font-medium">מבחן</th>
          <th className="px-2 py-1 text-start font-medium">נימוק</th>
        </tr>
      </thead>
      <tbody className="block align-top sm:table-row-group">
        {rows.map(([test, result, why]) => (
          <tr key={test} className="block border-t border-line/70 py-1 sm:table-row sm:py-0">
            <td className="block px-2 pt-1 font-semibold whitespace-nowrap text-fg sm:table-cell sm:py-1.5">
              {test}: {result}
            </td>
            <td className="block px-2 pb-1 sm:table-cell sm:py-1.5">{why}</td>
          </tr>
        ))}
        <tr className="block border-t-2 border-line font-bold text-fg sm:table-row">
          <td className="block px-2 py-1.5 sm:table-cell" colSpan={2}>
            {verdict}
          </td>
        </tr>
      </tbody>
    </table>
  );
}

